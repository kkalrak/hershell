import { CONVERSATION_RULE } from '../src/agent-instructions.ts';
import assert from 'node:assert/strict';
import { _electron as electron } from 'playwright-core';
import { mkdtempSync, writeFileSync, readFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir = mkdtempSync(path.join(os.tmpdir(), 'hershell-api-test-'));
const capture = path.join(dir, 'input.txt');
const fixture = path.join(dir, 'receiver.cjs');
const shellTokenFile = path.join(dir, 'shell-token');
// Emulate a CLI that ignores Enter during its first 500ms of paste handling.
writeFileSync(fixture, `require('fs').writeFileSync(${JSON.stringify(shellTokenFile)},process.env.HERSHELL_SHELL_TOKEN); process.stdin.setRawMode(true); process.stdin.resume(); process.stdout.write('\\x1b[?2004hREADY'); let input='', pastedAt=0; process.stdin.on('data', b => { const text=b.toString(); input += text; if(text.includes('\\x1b[201~')) pastedAt=Date.now(); if(text === '\\r' && pastedAt && Date.now()-pastedAt>=500) { require('fs').writeFileSync(${JSON.stringify(capture)}, input); process.stdout.write('\\x1b[?2004l'); process.exit(); } });`);

const app = await electron.launch({ args: ['.'], env: { ...process.env, HERSHELL_USER_DATA: path.join(dir, 'profile') } });
try {
  const page = await app.firstWindow();
  await page.waitForFunction(() => window.__hershell?.tail(3).includes('PS '));
  await page.click('.term.active .xterm-screen');
  await page.keyboard.type('cd C:\\work\\hershell'); await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#list li').title === 'C:\\work\\hershell');
  await page.click('#extensions');
  assert.equal(await page.locator('#extensions-dialog').isVisible(), true);
  await page.click('#copy-usage');
  await page.waitForFunction(() => document.querySelector('#copy-result').textContent.includes('복사했습니다'));
  const usage = await app.evaluate(({ clipboard }) => clipboard.readText());
  assert.ok(usage.includes(CONVERSATION_RULE));
  assert.match(usage, /붙여넣기와 Enter는 허셀이 처리한다/);
  assert.match(usage, /너는 Enter 따로 누르지 않는다/);
  assert.match(usage, /POST \/messages/);
  assert.match(usage, /현재 셸 ID: hershell/);
  assert.match(usage, /답장 오면 다음 말 보낸다/);
  assert.match(usage, /HTTP 전송 성공은 답장 아니다/);
  assert.match(usage, /단순 확인·마지막 답변에는 또 답장 요구 안 한다/);
  assert.match(usage, /답장 없으면 또 보내지 않는다. 사용자에게 알린다/);
  await page.screenshot({ path: path.join(dir, 'extensions.png') });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#extensions-dialog').isVisible(), false);
  const info = await page.evaluate(() => window.pty.agentInfo());
  const headers = { Authorization: `Bearer ${info.token}`, 'Content-Type': 'application/json' };
  assert.equal((await fetch(info.url + '/shells')).status, 401);
  assert.equal((await fetch(info.url + '/shells', { headers: { ...headers, Origin: 'http://example.com' } })).status, 401);
  await page.click('#add');
  await page.waitForFunction(() => document.querySelectorAll('#list li').length === 2 && window.__hershell.tail(3).includes('PS '));
  await page.keyboard.type('cd C:\\work\\hershell\\src'); await page.keyboard.press('Enter');
  await page.waitForFunction(() => [...document.querySelectorAll('#list li')].some(li => li.title === 'C:\\work\\hershell\\src'));
  const shells = await (await fetch(info.url + '/shells', { headers })).json();
  assert.equal(shells.length, 2);
  assert.deepEqual(shells.map(s => s.id), ['hershell', 'src']);
  const post = body => fetch(info.url + '/messages', { method: 'POST', headers, body: JSON.stringify(body) });
  assert.equal((await post({ from: 'hershell', to: 'missing', message: 'test' })).status, 404);
  assert.equal((await post({ from: 1, to: 2, message: 'old numeric ID' })).status, 400);
  assert.equal((await post({ from: 'hershell', to: 'src', message: '\x1btest' })).status, 400);
  await page.keyboard.type(`node "${fixture}"`);
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => window.__hershell.tail(5).includes('READY'));
  const own = await (await fetch(info.url + '/shells/me', { headers: { Authorization: 'Bearer ' + readFileSync(shellTokenFile, 'utf8') } })).json();
  assert.equal(own.id, 'src');
  await page.click('#add');
  await page.waitForFunction(() => document.querySelectorAll('#list li').length === 3 && window.__hershell.tail(3).includes('PS '));
  const reordered = await (await fetch(info.url + '/shells', { headers })).json();
  assert.equal(reordered.find(s => s.cwd === 'C:\\work\\hershell').id, 'hershell');
  assert.equal(reordered.find(s => s.cwd === 'C:\\work\\hershell\\src').id, 'src');
  // Target remains hidden and still receives the message without switching or checking state.
  await page.locator('#list li').filter({ has: page.locator('.title', { hasText: /^hershell$/ }) }).click();
  const message = '한글 검토 요청\n두 번째 줄';
  const response = await post({ from: 'hershell', to: 'src', message });
  assert.equal(response.status, 200);
  assert.deepEqual(await response.json(), { delivered: true });
  await page.waitForTimeout(500);
  assert.equal(readFileSync(capture, 'utf8'), `\x1b[200~[hershell hershell → src]\r${CONVERSATION_RULE}\r${message.replace(/\n/g, '\r')}\x1b[201~\r`);
  await page.locator('#list li').last().hover();
  await page.locator('#list li').last().locator('.close').click();
  await page.waitForTimeout(300);
  assert.equal((await post({ from: 'hershell', to: 'src', message: 'closed' })).status, 404);
  await page.click('#add');
  await page.waitForFunction(() => document.querySelectorAll('#list li').length === 3 && window.__hershell.tail(3).includes('PS '));
  const duplicates = await (await fetch(info.url + '/shells', { headers })).json();
  const homes = duplicates.filter(s => s.id !== 'hershell');
  assert.equal(homes.length, 2);
  assert.ok(homes.every(s => s.id === s.cwd));
  assert.equal((await post({ from: 'hershell', to: homes[0].id, message: 'ambiguous' })).status, 409);
  console.log('Agent API and modal checks passed. Folder routing survives reordering; ambiguous paths rejected. Artifacts:', dir);
} finally { await app.close(); }
